#!/usr/bin/env python3
"""Generate src/fsq_tables.c from fldigi 4.2.13's varicode sources (stdlib only).

    python3 tools/gen_tables.py /path/to/fldigi > src/fsq_tables.c

Copies the encode table (fsq_varicode / ifkp_varicode, [256][2]) and the decode table
(wsq_varidecode / ifkp_varidecode, 29 x 32) of src/fsq/fsq_varicode.cxx and
src/ifkp/ifkp_varicode.cxx verbatim (numbers only), so the C tables are fldigi's.
SPDX-License-Identifier: GPL-3.0-or-later
"""
import re
import sys
from pathlib import Path


def arrays(path):
    text = Path(path).read_text(encoding="latin-1")
    text = re.sub(r"//[^\n]*", "", text)
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    out = {}
    for m in re.finditer(r"int\s+(\w+)\s*\[[^\]]*\](?:\[2\])?\s*=\s*\{(.*?)\};", text, re.S):
        out[m.group(1)] = [int(v) for v in re.findall(r"-?\d+", m.group(2))]
    return out


def emit(name, vals, per, pairs):
    lines = []
    if pairs:
        rows = [vals[i:i + 2] for i in range(0, len(vals), 2)]
        for i in range(0, len(rows), 8):
            lines.append("    " + " ".join("{%2d,%2d}," % tuple(r) for r in rows[i:i + 8]))
        return "const signed char %s[256][2] = {\n%s\n};\n" % (name, "\n".join(lines))
    for i in range(0, len(vals), per):
        lines.append("    " + " ".join("%4d," % v for v in vals[i:i + per]))
    return "const short %s[%d] = {\n%s\n};\n" % (name, len(vals), "\n".join(lines))


def main():
    root = Path(sys.argv[1])
    fsq = arrays(root / "src/fsq/fsq_varicode.cxx")
    ifkp = arrays(root / "src/ifkp/ifkp_varicode.cxx")
    assert len(fsq["fsq_varicode"]) == 512 and len(ifkp["ifkp_varicode"]) == 512
    assert len(fsq["wsq_varidecode"]) == 29 * 32 == len(ifkp["ifkp_varidecode"])
    print("/*\n * fldigi-fsq-core varicode tables, generated by tools/gen_tables.py from fldigi "
          "4.2.13\n * src/fsq/fsq_varicode.cxx:1-75 and src/ifkp/ifkp_varicode.cxx:1-75 "
          "(numbers copied verbatim).\n * Do not edit by hand.\n"
          " * SPDX-License-Identifier: GPL-3.0-or-later\n */\n"
          '#include "fsq_internal.h"\n')
    print("/* encode: character -> {first symbol, second symbol} (fsq_varicode.cxx:1-34) */")
    print(emit("ffsq_fsq_varicode", fsq["fsq_varicode"], 0, True))
    print("/* decode: [prev * 32 + curr] -> character (fsq_varicode.cxx:44-75) */")
    print(emit("ffsq_fsq_varidecode", fsq["wsq_varidecode"], 16, False))
    print("/* encode (ifkp_varicode.cxx:1-34) */")
    print(emit("ffsq_ifkp_varicode", ifkp["ifkp_varicode"], 0, True))
    print("/* decode (ifkp_varicode.cxx:44-75) */")
    print(emit("ffsq_ifkp_varidecode", ifkp["ifkp_varidecode"], 16, False), end="")


if __name__ == "__main__":
    main()
